'use strict';
const assert = require('assert').strict;
const fs = require('fs');
const path = require('path');
const file = fs.readFileSync(path.join(__dirname, '../src/HttpServer.cpp'));
assert(!file.subarray(0, 3).equals(Buffer.from([0xef, 0xbb, 0xbf])), 'No UTF-8 BOM');
const source = file.toString('utf8');
const html = source.split('static const std::string html = R"HTML(')[1].split(')HTML";')[0];
assert.equal((html.match(/<style(?:\s[^>]*)?>/g) || []).length, 2);
assert.equal((source.match(/id="astra-skin"/g) || []).length, 1);
assert.match(html, /<style id="astra-skin">[\s\S]*<\/style>\s*<\/head>/);
const css = html.split('<style id="astra-skin">')[1].split('</style>')[0];
assert(!css.includes(')HTML"'));
assert.equal((css.match(/{/g) || []).length, (css.match(/}/g) || []).length);
for (const token of ['--main-bg-color', '--border-color', '--link-color', '--ok-color', '--err-color', '--select-color', '--border-radius']) assert(css.includes(token));
assert.match(css, /--main-bg-color:\s*hsl\(220,\s*10%,\s*20%\)/);
assert.match(css, /body:before\s*\{\s*display:\s*none\s*!important/);
assert.match(css, /\.tile:before\s*\{\s*display:\s*block/);
assert.match(css, /\.form-row input:not\(\[type=checkbox\]\)/);
assert(!/https?:\/\//i.test(css), 'Skin must not embed server addresses or external resources');
console.log('PASS: reversible dark skin, balanced CSS and no external dependencies');
